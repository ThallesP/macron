package steamhook

import (
	"go/format"
	"slices"
	"strings"
	"text/template"
)

type KnownBuild struct {
	ID      string
	Variant string
	Files   []KnownFile
	Client  ClientCode
}

type KnownFile struct {
	Path    string
	SHA256  string
	Package string
}

var rowsTemplate = template.Must(template.New("rows").Parse(`{{range .}}	{
		ID:      {{printf "%q" .ID}},
		Variant: {{printf "%q" .Variant}},
		Files: []KnownFile{
{{- range .Files}}
			{Path: {{printf "%q" .Path}}, SHA256: {{printf "%q" .SHA256}}, Package: {{printf "%q" .Package}}},
{{- end}}
		},
		Client: ClientCode{
			UUID:    {{printf "%q" .Client.UUID}},
			Enabled: {{template "instruction" .Client.Enabled}},
			Stop:    {{template "instruction" .Client.Stop}},
		},
	},
{{end}}{{define "instruction"}}Instruction{Address: {{printf "%#x" .Address}}, Original: {{printf "%#08x" .Original}}, Patched: {{printf "%#08x" .Patched}}}{{end}}`))

var headerTemplate = template.Must(template.New("header").Parse(`// Code generated by cmd/steam-builds from internal/steamhook/builds.go. DO NOT EDIT.
#include <stdint.h>

struct steam_instruction {
    uintptr_t address;
    uint32_t original;
    uint32_t patched;
};

struct steam_build {
    const char *id;
    const char *uuid;
    struct steam_instruction enabled;
    struct steam_instruction stop;
};

static const struct steam_build steam_builds[] = {
{{- range .}}
    {"{{.ID}}", "{{.Client.UUID}}", {{template "instruction" .Client.Enabled}}, {{template "instruction" .Client.Stop}}},
{{- end}}
};
{{define "instruction"}}{ {{printf "%#x" .Address}}, {{printf "%#08x" .Original}}, {{printf "%#08x" .Patched}} }{{end}}`))

func (k KnownBuild) matches(hashes map[string]string) bool {
	for _, file := range k.Files {
		if hashes[file.Path] != file.SHA256 {
			return false
		}
	}
	return len(k.Files) > 0
}

func (k KnownBuild) IsIn(table []KnownBuild) bool {
	hashes := map[string]string{}
	for _, file := range k.Files {
		hashes[file.Path] = file.SHA256
	}
	return slices.ContainsFunc(table, func(known KnownBuild) bool {
		return known.matches(hashes)
	})
}

func RenderRows(builds []KnownBuild) (string, error) {
	var rows strings.Builder
	if err := rowsTemplate.Execute(&rows, builds); err != nil {
		return "", err
	}
	return rows.String(), nil
}

// The switch library's table: one row per steamclient.dylib, whichever
// steam_osx variants ship with it.
func RenderHeader(builds []KnownBuild) (string, error) {
	var clients []KnownBuild
	for _, build := range builds {
		isListed := slices.ContainsFunc(clients, func(listed KnownBuild) bool {
			return listed.Client.UUID == build.Client.UUID
		})
		if !isListed {
			clients = append(clients, build)
		}
	}

	var header strings.Builder
	if err := headerTemplate.Execute(&header, clients); err != nil {
		return "", err
	}
	return header.String(), nil
}

func RenderTable(builds []KnownBuild) ([]byte, error) {
	rows, err := RenderRows(builds)
	if err != nil {
		return nil, err
	}
	return format.Source([]byte("package steamhook\n\nvar KnownBuilds = []KnownBuild{\n" + rows + "}\n"))
}
